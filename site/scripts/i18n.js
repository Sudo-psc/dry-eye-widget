  const HTML_KEYS = new Set(["hero.title", "cost.book.note"]);

  function apply(lang) {
    const dict = STR[lang] || STR.pt;
    document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = dict[key];
      if (val == null) return;
      if (HTML_KEYS.has(key)) el.innerHTML = val;
      else el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      const val = dict[key];
      if (val != null) el.setAttribute("aria-label", val);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      const val = dict[key];
      if (val != null) el.setAttribute("title", val);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      const key = el.getAttribute("data-i18n-alt");
      const val = dict[key];
      if (val != null) el.setAttribute("alt", val);
    });
    document.querySelectorAll(".lang-switch button").forEach((b) => {
      b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
    });
    try { localStorage.setItem("dew-lang", lang); } catch (e) {}
    try {
      // Secure em HTTPS; SameSite=Lax reduz CSRF de cookie de preferência.
      var secure = location.protocol === "https:" ? "; Secure" : "";
      document.cookie =
        "dew-lang=" + lang + "; path=/; max-age=31536000; SameSite=Lax" + secure;
    } catch (e) {}
    // Atualiza aria-label do seletor de idioma e do tema (se presentes).
    var group = document.querySelector(".lang-switch");
    if (group) {
      group.setAttribute("aria-label", lang === "en" ? "Language" : "Idioma");
    }
    var themeBtn = document.getElementById("theme-toggle");
    if (themeBtn) {
      themeBtn.setAttribute(
        "aria-label",
        lang === "en" ? "Toggle theme" : "Alternar tema",
      );
    }
    document.dispatchEvent(new CustomEvent("dew:langchange", {
      detail: { lang: lang },
    }));
  }

  function readCookieLang() {
    try {
      const m = document.cookie.match(/(?:^|;\s*)dew-lang=(pt|en)(?:;|$)/);
      return m ? m[1] : null;
    } catch (e) { return null; }
  }

  function detectLang() {
    // Preferência explícita: cookie (setado pelo nginx em /app/pt|/app/en
    // ou por visita anterior) > localStorage.
    const fromCookie = readCookieLang();
    if (fromCookie) return fromCookie;
    try {
      const stored = localStorage.getItem("dew-lang");
      if (stored === "pt" || stored === "en") return stored;
    } catch (e) {}
    // Primeira visita: idioma conforme a localização/idioma do navegador.
    const langs = (navigator.languages && navigator.languages.length)
      ? navigator.languages
      : [navigator.language || "pt-BR"];
    for (const l of langs) {
      const low = String(l).toLowerCase();
      if (low.startsWith("pt")) return "pt";
      if (low.startsWith("en")) return "en";
    }
    return "en";
  }

  window.dewSetLang = apply;
  window.dewInitLang = function () {
    apply(detectLang());
  };
